package com.rustyrazorblade.easydblab

import com.fasterxml.jackson.databind.ObjectMapper
import com.rustyrazorblade.easydblab.core.YamlDelegate
import io.github.oshai.kotlinlogging.KotlinLogging
import org.koin.core.component.KoinComponent
import java.io.File

data class Context(
    val easyDbLabUserDirectory: File,
    /**
     * Indicates if running in an interactive mode (the REPL) where
     * resources like CQL sessions should be kept open across commands.
     * Mutable so REPL can set this after context creation.
     */
    var isInteractive: Boolean = false,
    /**
     * Working directory for lab operations (cluster state, logs, etc.).
     * Must be absolute. Every workspace file resolves against it, never against the JVM's
     * current directory; only `ContextFactory.processStartDirectory` reads `user.dir`.
     */
    val workingDirectory: File,
    /**
     * The install directory the start script reports through `easydblab.apphome`: the parent of
     * `lib/`, `packer/` and `agents/`. Tests supply their own.
     */
    val appHome: String? = System.getProperty("easydblab.apphome"),
) : KoinComponent {
    companion object {
        /** The build number the start script passes as `easydblab.version`; 0 when run without it or when it is not a number. */
        fun buildVersion(): Int = System.getProperty("easydblab.version")?.toIntOrNull() ?: 0

        /** The profile `EASY_DB_LAB_PROFILE` names: `default` when it is unset or empty. */
        internal fun profileName(envValue: String?): String = envValue?.ifEmpty { null } ?: "default"
    }

    init {
        require(workingDirectory.isAbsolute) { "The workspace directory must be absolute: $workingDirectory" }
    }

    val log = KotlinLogging.logger {}

    /**
     * Profile setup.  User can override the default profile using a env var.
     * Long term, should probably make this something they can do via a command.
     * Will be useful once multiple cloud providers are supported.
     */
    var profile = profileName(System.getenv("EASY_DB_LAB_PROFILE"))
    var profilesDir = File(easyDbLabUserDirectory, "profiles")
    var profileDir = File(profilesDir, profile).also { it.mkdirs() }

    /**
     * Resolves [name] inside the workspace ([workingDirectory]), never against the JVM current
     * directory, with the checks of [resolveInWorkspace].
     */
    fun workspaceFile(name: String): File = resolveInWorkspace(workingDirectory, name)

    /**
     * [workspaceFile] for a file about to be written: a symbolic link at the final path is removed
     * first ([resolveInWorkspaceForWrite]), so the write stays inside the workspace.
     */
    fun workspaceFileForWrite(name: String): File = resolveInWorkspaceForWrite(workingDirectory, name)

    /**
     * [workspaceFile] for a directory the CLI writes files into: the directory itself, with its
     * links followed, must be inside the workspace ([resolveDirInWorkspace]).
     */
    fun workspaceDir(name: String): File = resolveDirInWorkspace(workingDirectory, name)

    /**
     * Version is either supplied by the in-repo script,
     * or the version generated by the application plugin
     */
    val version = buildVersion()
    val packerHome = "$appHome/packer/"
    val cassandraVersionsExtra = File(profileDir, "cassandra_versions")

    /**
     * Please use this for reading and writing yaml to objects
     *
     * Example usage:
     *
     * val state = mapper.readValue<MyStateObject>(json)
     */
    val yaml: ObjectMapper by YamlDelegate()
}
